import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
await mkdir('test-results/academy-world',{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1360,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto((process.env.ACADEMY_TEST_URL??'http://127.0.0.1:5190/web-hub')+'/games/academy-survival/?view=catalog&kind=features');
 const sourceDate=await page.getByRole('button',{name:'현재 게임 날짜 상세',exact:true}).innerText();
 await page.getByRole('button',{name:'시뮬레이션',exact:true}).click();
 await page.getByRole('heading',{name:'세계 시뮬레이션 · 관찰·통제',exact:true}).waitFor();
 await page.getByText('새 세계 설정·저장 불러오기',{exact:true}).click();
 await page.getByLabel('사용자 지정 NPC 수',{exact:true}).fill('10');
 await page.getByRole('button',{name:'새 세계 생성',exact:true}).click();
 assert.match(await page.getByRole('status').innerText(),/생성된 NPC 10명/);
 await page.getByLabel('세계 배속',{exact:true}).selectOption('360');
 const initialDate=await page.getByLabel('시뮬레이션 현재 시각',{exact:true}).innerText();
 await page.getByRole('button',{name:'재생',exact:true}).click();
 await page.waitForFunction(before=>document.querySelector('[aria-label="시뮬레이션 현재 시각"]').textContent!==before,initialDate);
 await page.getByRole('button',{name:'일시정지',exact:true}).click();
 const pausedDate=await page.getByLabel('시뮬레이션 현재 시각',{exact:true}).innerText();
 await page.waitForTimeout(350);
 assert.equal(await page.getByLabel('시뮬레이션 현재 시각',{exact:true}).innerText(),pausedDate);
 await page.getByRole('button',{name:'개발자 통제',exact:true}).click();
 await page.getByRole('button',{name:'AI 일시정지',exact:true}).click();
 await page.getByLabel('욕구 수치',{exact:true}).fill('90');
 await page.getByRole('button',{name:'욕구 변경',exact:true}).click();
 assert.equal(await page.getByRole('alert').count(),0);
 await page.getByRole('button',{name:'AI 재개',exact:true}).click();
 await page.getByRole('button',{name:'장소 관찰',exact:true}).click();
 await page.getByRole('heading',{name:'장소 관찰',exact:true}).waitFor();
 await page.getByRole('button',{name:'조직 관찰',exact:true}).click();
 await page.getByRole('heading',{name:'조직별 직접 소속 · 개발자 관찰',exact:true}).waitFor();
 await page.getByRole('button',{name:'사건·인과관계',exact:true}).click();
 await page.getByRole('button',{name:'인과관계 그래프',exact:true}).click();
 await page.getByRole('button',{name:'저장·검사',exact:true}).click();
 await page.getByRole('button',{name:'세계 정합성 검사',exact:true}).click();
 assert(!/error:/.test(await page.getByLabel('정합성 결과',{exact:true}).innerText()));
 await page.getByRole('button',{name:'세계 JSON 저장',exact:true}).click();
 const json=await page.getByLabel('세계 스냅샷 JSON',{exact:true}).inputValue(),saved=JSON.parse(json);
 assert.equal(saved.version,'world-simulation-v1');assert(saved.commands.some(c=>c.command.type==='need'));
 await page.getByRole('button',{name:'+1분',exact:true}).click();
 await page.getByText('1분 진행',{exact:true}).waitFor();
 const beforeBadLoad=await page.getByLabel('시뮬레이션 현재 시각',{exact:true}).innerText();
 await page.getByLabel('불러올 세계 JSON',{exact:true}).fill('{"version":"unknown"}');
 await page.getByRole('button',{name:'세계 JSON 불러오기',exact:true}).click();
 await page.getByRole('alert').waitFor();
 assert.equal(await page.getByLabel('시뮬레이션 현재 시각',{exact:true}).innerText(),beforeBadLoad,'bad load preserves current world');
 await page.getByLabel('불러올 세계 JSON',{exact:true}).fill(json);
 await page.getByRole('button',{name:'세계 JSON 불러오기',exact:true}).click();
 assert.equal(await page.getByLabel('시뮬레이션 현재 시각',{exact:true}).innerText(),pausedDate);
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.screenshot({path:'test-results/academy-world/mobile.png',fullPage:true});
 await page.getByRole('button',{name:'닫기',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'현재 게임 날짜 상세',exact:true}).innerText(),sourceDate);
 await page.getByRole('button',{name:'시뮬레이션',exact:true}).click();
 await page.getByRole('heading',{name:'세계 시뮬레이션 · 관찰·통제',exact:true}).waitFor();
 assert.match(await page.getByRole('status').innerText(),/생성된 NPC 1명/);
 assert.deepEqual(errors,[]);
 console.log('World UI passed: fresh 10 NPC, playback/pause, need and AI control, location/organization/graph, diagnosis, JSON restore, mobile, source isolation.');
}finally{await browser.close();}
